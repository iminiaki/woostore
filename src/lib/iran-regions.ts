const PERSIAN_DIGITS = "۰۱۲۳۴۵۶۷۸۹"
const ARABIC_DIGITS = "٠١٢٣٤٥٦٧٨٩"

/** Converts Persian and Arabic digits to ASCII so they can be validated and stored. */
export function toAsciiDigits(value: string) {
  return value.replace(/[۰-۹٠-٩]/g, (ch) => {
    const p = PERSIAN_DIGITS.indexOf(ch)
    return String(p >= 0 ? p : ARABIC_DIGITS.indexOf(ch))
  })
}

/** Iranian postal codes are exactly 10 digits. */
export function isIranPostcode(value: string) {
  return /^\d{10}$/.test(toAsciiDigits(value).replace(/[\s-]/g, ""))
}

/** Iranian mobile numbers: 09xxxxxxxxx, also accepting +98 / 0098 prefixes. */
export function normalizeIranMobile(value: string) {
  const digits = toAsciiDigits(value).replace(/[\s()-]/g, "")
  const local = digits.replace(/^(\+98|0098|98)(?=9\d{9}$)/, "0")
  return /^09\d{9}$/.test(local) ? local : null
}
